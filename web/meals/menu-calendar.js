const calendarWeekdays = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'];
const editions = [launchWeek];
for (let start = 0; start < additionalMeals.length; start += 7) {
  const weekNumber = start / 7 + 2;
  const week = additionalMeals.slice(start, start + 7).map((entry, day) => {
    const stem = 'w' + weekNumber + '-' + calendarWeekdays[day];
    return {
      cook: { ...entry, image: stem + '-cook.webp' },
      dine: { name: entry.outside, note: entry.outNote, image: stem + '-dine.webp' },
    };
  });
  editions.push(week);
}

const firstMonday = Date.UTC(2026, 10, 23) / 86400000;
const modulo = (value, size) => ((value % size) + size) % size;

function mealForDay(day) {
  const daysSinceLaunch = day - firstMonday;
  const week = Math.floor(daysSinceLaunch / 7);
  const cycle = Math.floor(week / editions.length);
  const edition = editions[modulo(week, editions.length)];
  const weekday = modulo(daysSinceLaunch, 7);
  // 다음 4주 편성 때 집밥과 외식의 요일을 서로 다르게 이동한다.
  return {
    cook: edition[modulo(weekday + cycle, 7)].cook,
    dine: edition[modulo(weekday - cycle, 7)].dine,
  };
}
